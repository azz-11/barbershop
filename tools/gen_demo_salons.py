def deposit_for(kind):
    if kind == "bridal":
        return {"mode": "smart", "type": "percent", "amount": 30, "cancelHours": 24,
                "rules": {"noShows": {"on": True, "min": 2}, "total": {"on": True, "min": 500},
                          "peak": {"on": False, "days": [4, 5], "from": 18, "to": 22}}}
    if kind == "henna":
        return {"mode": "all", "type": "fixed", "amount": 50, "cancelHours": 12,
                "rules": {"noShows": {"on": True, "min": 2}, "total": {"on": False, "min": 200},
                          "peak": {"on": False, "days": [4, 5], "from": 18, "to": 22}}}
    if kind == "groom":
        return {"mode": "smart", "type": "fixed", "amount": 50, "cancelHours": 6,
                "rules": {"noShows": {"on": True, "min": 2}, "total": {"on": True, "min": 250},
                          "peak": {"on": True, "days": [4, 5], "from": 19, "to": 24}}}
    if kind == "smart":
        return {"mode": "smart", "type": "fixed", "amount": 40, "cancelHours": 4,
                "rules": {"noShows": {"on": True, "min": 2}, "total": {"on": True, "min": 300},
                          "peak": {"on": True, "days": [4, 5], "from": 18, "to": 23}}}
    return None

def build(entry, idx, women):
    sid, name, tagline, slogan, about, groups, extra = entry
    ai = extra.get("area", idx % len(AREAS))
    area, lat, lng, street = AREAS[ai]
    lat += random.uniform(-0.006, 0.006); lng += random.uniform(-0.006, 0.006)
    cat = W if women else M
    services = []
    for g in groups:
        items = cat[g]
        k = len(items) if len(items) <= 3 else random.randint(max(3, len(items) - 3), len(items))
        chosen = sorted(random.sample(range(len(items)), k))
        for i in chosen:
            s_id, s_name, desc, mins, (lo, hi) = items[i]
            services.append({"id": s_id, "name": s_name, "desc": desc, "min": mins, "price": rp(lo, hi), "group": g})
    if len(groups) == 1:
        for s in services: s.pop("group")
    # الفريق
    pool = W_NAMES if women else M_NAMES
    names = random.sample(pool, random.randint(2, 4) if women else random.randint(2, 4))
    staff = []
    for i, n in enumerate(names):
        role = W_ROLE[groups[i % len(groups)]] if women else (M_ROLES[0] if i == 0 else random.choice(M_ROLES[1:]))
        years = random.randint(3, 15)
        staff.append({"id": "abcdefgh"[i], "name": n, "role": role, "years": years,
                      "seedCuts": years * random.randint(30, 60)})
    staff.sort(key=lambda m: -m["years"])
    for i, m in enumerate(staff): m["id"] = "abcdefgh"[i]
    # الإحصاءات (أرقام تجريبية)
    visits = sum(m["seedCuts"] for m in staff) + random.randint(80, 400)
    rated = int(visits * random.uniform(0.25, 0.35))
    very = int(rated * random.uniform(0.74, 0.88)); no = int(rated * random.uniform(0.02, 0.06))
    ok = rated - very - no
    pal = random.choice(PALETTE_W if women else PALETTE_M)
    if women:
        hours = random.choice([{"open": 10, "close": 22}, {"open": 12, "close": 23}, {"open": 13, "close": 23}, {"open": 10, "close": 21}])
    else:
        hours = random.choice([{"open": 14, "close": 24}, {"open": 9, "close": 24}, {"open": 16, "close": 24}, {"open": 10, "close": 23}])
    s = {
        "id": sid, "demo": True, "name": name, "type": "women" if women else "men", "tagline": tagline,
        "area": area, "slogan": slogan, "about": about, "address": f"جدة، {area}، {street}",
        "location": {"lat": round(lat, 4), "lng": round(lng, 4)},
        "seed": {"visits": visits, "ratings": {"very": very, "ok": ok, "no": no}},
        "brand": {"primary": pal[0], "accent": pal[1]}, "hours": hours,
        "assets": False,
        "demoSub": DEMO_SUB_POOL[idx % len(DEMO_SUB_POOL)],
    }
    if extra.get("closed"): s["closedDays"] = extra["closed"]
    if extra.get("queue"): s["queue"] = {"enabled": True, "remote": True, "max": random.choice([6, 8, 10])}
    dep = deposit_for(extra.get("deposit"))
    if dep: s["deposit"] = dep
    s["services"] = services
    # المنتجات لنحو نصف الصوالين
    if random.random() < 0.55:
        if women:
            cands = [p for g in groups for p in PROD_W.get(g, [])]
        else:
            cands = PROD_M
        picks = random.sample(cands, min(len(cands), random.randint(2, 3)))
        s["productsEnabled"] = True
        s["products"] = [{"id": p[0], "name": p[1], "category": p[2], "price": rp(*p[3]), "desc": p[4], "inStock": random.random() > 0.15} for p in picks]
    s["staff"] = staff
    return s

